def test_deleting_a_judge_leaves_the_audit_trail_intact(
    raw, query, graph, mark_audit_entries
):
    """Verdicts are personal data; the audit trail is the record of what happened.

    Deleting the judge removes their verdicts (CASCADE). The trail is not touched
    at all: `actor_id` is the id the judge had when the entry was written and
    `actor_email` is the durable attribution, so history survives verbatim. That is
    the point of migration 0005 — with `ON DELETE SET NULL` still in place,
    PostgreSQL tried to anonymise the row, the append-only trigger refused the
    UPDATE, and the delete itself failed.
    """
    marker = mark_audit_entries()
    raw(
        "INSERT INTO audit_logs (actor_id, actor_email, action, entity) "
        "VALUES (:actor_id, :email, 'score.technical_submitted', 'score')",
        {"actor_id": graph["judge"].id, "email": graph["judge"].email},
    )

    raw("DELETE FROM users WHERE id = :id", {"id": graph["judge"].id})

    assert query("SELECT count(*) FROM scores WHERE judge_id = :id", {"id": graph["judge"].id})[0][0] == 0
    rows = query(
        "SELECT actor_id, actor_email, action FROM audit_logs WHERE id > :marker",
        {"marker": marker},
    )
    assert rows == [
        (graph["judge"].id, graph["judge"].email, "score.technical_submitted")
    ]


