def test_email_uniqueness_is_case_sensitive_in_the_database(raw, query, graph):
    """The database compares exactly; the API is what folds case.

    `schemas.RegisterRequest` lowercases the address before it reaches SQLAlchemy,
    so the API cannot create `A@x.dev` next to `a@x.dev`. A bulk import that
    bypasses the schema could — a duplicate-looking roster is therefore something
    an importer has to normalise itself rather than something the index prevents.
    """
    raw(INSERT_USER, {"email": "Case@test.dev", "name": "Upper", "role": "participant"})
    raw(INSERT_USER, {"email": "case@test.dev", "name": "Lower", "role": "participant"})
    assert query("SELECT count(*) FROM users WHERE lower(email) = 'case@test.dev'")[0][0] == 2
