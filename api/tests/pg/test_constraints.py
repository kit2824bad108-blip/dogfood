"""Database constraints, tested against PostgreSQL directly.

Every insert here goes through SQL, not through the API. That is deliberate: the
question is not whether a router validates its payload — the pydantic schemas and
the router tests already answer that — but whether the invariant survives a writer
that never touches the router. Anything enforced only in Python would pass those
tests and fail these.

Assertions name the constraint that refused the write, or the SQLSTATE class when
the name is generated by PostgreSQL (a foreign key declared inline is named by the
server): 23505 unique, 23503 foreign key, 23502 not null, 23514 check.

Each violating statement is written so exactly one invariant can fire. A row that
broke a foreign key *and* a check would make the assertion a coin toss.
"""
