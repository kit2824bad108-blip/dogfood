# ── the writers the application actually uses ─────────────────────────────────


def test_the_orm_cannot_bypass_a_constraint_either(db, graph, constraint_name):
    """The API's writer is SQLAlchemy; a constraint has to hold for it too."""
    db.add(Team(name="Constraint Team", invite_code="ORM00001"))
    with pytest.raises(IntegrityError) as info:
        db.commit()
    db.rollback()
    assert constraint_name(info.value) == "uq_teams_name"


def test_an_audit_entry_written_through_the_orm_is_append_only(db, graph):
    entry = AuditLog(action="constraints.probe", actor_id=graph["organizer"].id)
    db.add(entry)
    db.commit()
    entry_id = entry.id

    entry.action = "constraints.rewritten"
    # The trigger raises, so this is a database error rather than a constraint
    # violation: `IntegrityError` would mean a uniqueness or foreign-key rule.
    with pytest.raises(ProgrammingError) as info:
        db.commit()
    db.rollback()
    assert "append-only" in str(info.value), "the trigger, not the API, refused this"

    db.expire_all()
    assert db.get(AuditLog, entry_id).action == "constraints.probe"


def test_duplicate_review_through_the_orm_is_refused(db, graph, constraint_name):
    other_team = Team(name="ORM Dup Team", invite_code="ORMDUP01")
    db.add(other_team)
    db.flush()
    other = Submission(
        team_id=other_team.id,
        title="ORM Duplicate",
        repo_url="https://github.com/orm/duplicate",
        status="submitted",
    )
    db.add(other)
    db.flush()
    db.add(DuplicateReview(submission_id=other.id, duplicate_of_submission_id=graph["submission"].id))
    db.commit()

    db.add(DuplicateReview(submission_id=other.id, duplicate_of_submission_id=graph["submission"].id))
    with pytest.raises(IntegrityError) as info:
        db.commit()
    db.rollback()
    assert constraint_name(info.value) == "uq_duplicate_pair"


