"""Fixture import: load a messy real-world dataset, diagnose it, apply it.

Real events arrive with problems, and a platform that only copes with a curated
demo is not a platform. This module is built for the cases that actually hurt:

  * **incomplete review batches** — assignments with no verdict. A missing score
    is *missing*, never zero, and coverage is reported rather than assumed;
  * **a zero-variance judge** (every verdict identical) and a **single-verdict
    judge** — the two degenerate cases `zscore` guards against. Both are
    *detected from the data*, not read from a note in the file, so the detector
    can be checked independently of the dataset's own claims;
  * **duplicate submissions** — detected by comparing normalised repository URLs
    and title fingerprints. Detection is deterministic and recomputed on demand;
    only an organiser's decision is persisted (`duplicate_reviews`);
  * **missing comments and summaries** — nulls stay null all the way through;
  * **string identifiers** — every imported row keeps its source key in
    `source_ref`, so an import is idempotent and traceable;
  * **a closed event window** — imported deadlines are respected, never
    "helpfully" reopened.

The fixture file is Axion's own (`fixtures.json`, generated by
`api/scripts/build_fixtures.py`). No organiser-provided fixture set existed when
this was built, and nothing here pretends otherwise.
"""
